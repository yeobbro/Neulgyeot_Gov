/**
 * Which FactBook facts may leave Gov for an AI provider (pure, testable).
 *
 * Default-deny. A fact is sendable only if:
 *  1. its (sourceType, field) is on the allowlist, AND
 *  2. for "vocab" fields, every value is an exact member of a controlled vocabulary
 *     (field names are not enough: e.g. seed data has household_type "독거, 인근 거주 자녀 주 1회 방문"), AND
 *  3. the final text passes the identifier guard (phone, RRN, e-mail, card/account-like digit runs).
 * Everything typed freely by people (hospital social-worker note, assessment answers, missing-item notes,
 * plan frequency/notes, home safety notes, …) is "free_text" and is never sent unless a future, separately
 * approved tenant setting allows it — and even then the identifier guard still applies. Regex guards cannot
 * detect names, which is why free text stays excluded by default.
 *
 * Inventory source: lib/server/services/ai.ts referralFacts()/caseFacts()/rule engines @ this branch.
 */
import type { Fact } from "../../domain/ai-draft";
import { SERVICE_TYPE_LABEL } from "../../domain/enums";

export type FactClass = "system" | "vocab" | "free_text";
declare const providerRecordBrand: unique symbol;
/** A record that passed this policy. Only selectSendableFacts() creates it, so a provider client cannot be
 * handed raw FactBook facts by mistake (type-level separation of the rule FactBook and the provider payload). */
export type ProviderRecord = { readonly id: string; readonly text: string; readonly [providerRecordBrand]: true };
/** @deprecated use ProviderRecord */
export type SendableFact = ProviderRecord;
export type ExcludedFact = { id: string; reason: "never_send" | "free_text" | "not_allowlisted" | "vocab_mismatch" | "identifier_pattern" };

/** Never sent to any provider, whatever the options (not even its presence): checked before everything else. */
const NEVER_SEND: Array<[string, string | RegExp]> = [
  ["referral_payload", "livingNeeds.socialWorkerNote"],
  ["referral_payload", /^subject\./],
  ["recipient_identity", /.*/],
];
export const isNeverSend = (f: Pick<Fact, "sourceType" | "field">) =>
  NEVER_SEND.some(([t, field]) => f.sourceType === t && (typeof field === "string" ? f.field === field : field.test(f.field)));

/* Controlled vocabularies: Hospital→Municipality referral contract v1.0 labels (yeobbro/Neulgyeot
 * lib/integrations/municipal-referral/types.ts, lib/hospital/types.ts) and Gov's own enums/seed values. */
const LIVING = ["독거", "배우자와 동거", "가족과 동거", "기타"];
const HOUSING = ["아파트 (승강기 있음)", "아파트", "단독주택", "다세대·연립", "기타"];
const BARRIERS = ["계단", "욕실 접근성", "이동 동선·출입", "기타"];
const HOSPITAL_SERVICES = ["방문 간호", "식사 지원", "주거 개선", "이동 지원", "일상생활 지원", "기타"];
const SERVICES = [...HOSPITAL_SERVICES, ...Object.values(SERVICE_TYPE_LABEL)];
const KADL = ["자립", "부분 도움", "완전 도움"];
const COGNITION = ["일상 의사소통 가능", "일부 도움 필요", "상시 도움 필요", "추가 평가 필요"];
const HOUSEHOLD = ["독거", "부부 가구", "자녀 동거", "기타", "1인 가구"];
const AGE_BANDS = ["50대", "60대", "70대", "80대", "90대", "100세 이상"];

type Rule = { cls: "system" } | { cls: "vocab"; check: (value: string) => boolean } | { cls: "free_text" };

const inList = (vocab: string[]) => (v: string) => vocab.includes(v.trim());
const listOf = (vocab: string[]) => (v: string) => v.split(",").map((x) => x.trim()).filter(Boolean).every((x) => vocab.includes(x));
/** "식사 자립, 이동 부분 도움, 화장실 부분 도움" */
const kadl = (v: string) => {
  const m = v.match(/^식사 (.+), 이동 (.+), 화장실 (.+)$/);
  return Boolean(m && [m[1], m[2], m[3]].every((x) => KADL.includes(x.trim())));
};
const FREQ = /^(매일|주\s?\d{1,2}회|월\s?\d{1,2}회|격주\s?\d{1,2}회|수시)$/;
/** "식사 지원 주 3회, 방문간호 주 1회" — service label + simple frequency only */
const planItems = (v: string) =>
  v.split(",").map((x) => x.trim()).filter(Boolean).every((item) => {
    const svc = SERVICES.find((s) => item.startsWith(s + " "));
    return Boolean(svc && FREQ.test(item.slice(svc.length + 1).trim()));
  });

const key = (sourceType: string, field: string) => `${sourceType}|${field}`;
const RULES: Record<string, Rule> = {
  // generated by Gov itself (codes, dates, labels, counts, names of Gov region units)
  [key("referral_payload", "discharge.plannedDate")]: { cls: "system" },
  [key("incoming_referral", "status")]: { cls: "system" },
  [key("incoming_referral", "region_unit_id")]: { cls: "system" },
  [key("consent_evidence", "decision")]: { cls: "system" },
  [key("care_case", "region_unit_id")]: { cls: "system" },
  [key("needs_assessment", "answer_status")]: { cls: "system" },
  [key("provider_match", "candidates")]: { cls: "system" },
  [key("case_record", "occurred_at")]: { cls: "system" },
  [key("service_referral", "status")]: { cls: "system" },
  [key("support_plan_item", "service_type")]: { cls: "system" },
  [key("action_task", "status")]: { cls: "system" },
  // short strings from the hospital / staff that are safe only when they are a known label
  [key("referral_payload", "livingNeeds.livingArrangement")]: { cls: "vocab", check: inList(LIVING) },
  [key("referral_payload", "livingNeeds.housingType")]: { cls: "vocab", check: inList(HOUSING) },
  [key("referral_payload", "livingNeeds.barriers")]: { cls: "vocab", check: listOf(BARRIERS) },
  [key("referral_payload", "livingNeeds.requestedServices")]: { cls: "vocab", check: listOf(SERVICES) },
  [key("referral_payload", "functionalSummary.kAdl")]: { cls: "vocab", check: kadl },
  [key("referral_payload", "functionalSummary.cognition")]: { cls: "vocab", check: inList(COGNITION) },
  [key("care_recipient", "age_band")]: { cls: "vocab", check: inList(AGE_BANDS) },
  [key("care_recipient", "household_type")]: { cls: "vocab", check: inList(HOUSEHOLD) },
  [key("support_plan", "items")]: { cls: "vocab", check: planItems },
  // typed freely by people
  [key("incoming_referral", "missing_items")]: { cls: "free_text" },
  [key("home_environment", "barriers")]: { cls: "free_text" },
};

export function classifyFact(f: Fact): FactClass | "unknown" {
  if (f.sourceType === "assessment_item") return "free_text";
  return RULES[key(f.sourceType, f.field)]?.cls ?? "unknown";
}

/** Value part of Gov's `${label}: ${value}` fact text (whole text if there is no label). */
export function factValue(text: string) {
  const i = text.indexOf(": ");
  return i >= 0 ? text.slice(i + 2) : text;
}

const IDENTIFIER_PATTERNS: RegExp[] = [
  /\b\d{6}\s*-\s*[1-8]\d{6}\b/, // resident registration number
  /\b01[016789][-.\s]?\d{3,4}[-.\s]?\d{4}\b/, // mobile
  /\b0(?:2|[3-6][1-5])[-.\s]?\d{3,4}[-.\s]?\d{4}\b/, // landline
  /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/, // e-mail
  /\d{7,}/, // long digit runs (card, account, patient numbers)
  /(?:\d{4}[-\s]){3}\d{4}/, // card
];
export const hasIdentifierPattern = (text: string) => IDENTIFIER_PATTERNS.some((p) => p.test(text));

export function selectSendableFacts(facts: Fact[], opts: { allowFreeText?: boolean } = {}): { sendable: ProviderRecord[]; excluded: ExcludedFact[] } {
  const sendable: ProviderRecord[] = [];
  const excluded: ExcludedFact[] = [];
  for (const f of facts) {
    if (isNeverSend(f)) {
      excluded.push({ id: f.id, reason: "never_send" });
      continue;
    }
    const rule = f.sourceType === "assessment_item" ? ({ cls: "free_text" } as Rule) : RULES[key(f.sourceType, f.field)];
    if (!rule) {
      excluded.push({ id: f.id, reason: "not_allowlisted" });
      continue;
    }
    if (rule.cls === "free_text" && !opts.allowFreeText) {
      excluded.push({ id: f.id, reason: "free_text" });
      continue;
    }
    if (rule.cls === "vocab" && !rule.check(factValue(f.text))) {
      excluded.push({ id: f.id, reason: "vocab_mismatch" });
      continue;
    }
    if (hasIdentifierPattern(f.text)) {
      excluded.push({ id: f.id, reason: "identifier_pattern" });
      continue;
    }
    sendable.push({ id: f.id, text: f.text } as ProviderRecord);
  }
  return { sendable, excluded };
}
